import { ColorItem } from '@/types';
import { getApproximateColorName } from '../color/names';

/**
 * Generates CSS Variables string
 * e.g.
 * :root {
 *   --color-1: #A1E3F9; /* Ice Blue * /
 * }
 */
export function generateCssVariables(colors: ColorItem[], paletteName: string = 'MoPalette'): string {
  const lines = [
    `/* ${paletteName} — Generated by MoPalette */`,
    `:root {`,
    ...colors.map((c, i) => {
      const name = c.name || getApproximateColorName(c.hex);
      return `  --color-${i + 1}: ${c.hex}; /* ${name} */`;
    }),
    `}`,
  ];
  return lines.join('\n');
}

/**
 * Generates SCSS Variables string
 */
export function generateScssVariables(colors: ColorItem[], paletteName: string = 'MoPalette'): string {
  const lines = [
    `// ${paletteName} — Generated by MoPalette`,
    ...colors.map((c, i) => {
      const name = c.name || getApproximateColorName(c.hex);
      const varName = `$color-${i + 1}`;
      return `${varName}: ${c.hex}; // ${name}`;
    }),
  ];
  return lines.join('\n');
}

/**
 * Generates Tailwind CSS colors config object string
 */
export function generateTailwindConfig(colors: ColorItem[], paletteName: string = 'MoPalette'): string {
  const obj: Record<string, string> = {};
  colors.forEach((c, i) => {
    obj[`palette-${i + 1}`] = c.hex;
  });

  return `// Tailwind CSS configuration snippet for ${paletteName}
// Add this inside module.exports = { theme: { extend: { colors: { ... } } } }
module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(obj, null, 2)}
    }
  }
};`;
}

/**
 * Generates standardized JSON export
 */
export function generateJsonExport(colors: ColorItem[], paletteName: string = 'MoPalette'): string {
  const data = {
    app: 'MoPalette',
    version: '1.0.0',
    exportedAt: new Date().toISOString(),
    name: paletteName,
    colors: colors.map((c, index) => ({
      index: index + 1,
      hex: c.hex,
      name: c.name || getApproximateColorName(c.hex),
      locked: !!c.locked,
    })),
  };
  return JSON.stringify(data, null, 2);
}

/**
 * Generates Plain TXT color list
 */
export function generateTxtList(colors: ColorItem[]): string {
  return colors
    .map((c) => `${c.hex}  ${c.name || getApproximateColorName(c.hex)}`)
    .join('\n');
}

/**
 * Generates GPL (GIMP / Inkscape Palette) file
 */
export function generateGplPalette(colors: ColorItem[], paletteName: string = 'MoPalette'): string {
  const lines = [
    'GIMP Palette',
    `Name: ${paletteName}`,
    'Columns: 4',
    '# Palette exported from MoPalette (https://mopalette.app)',
  ];

  for (const c of colors) {
    const clean = c.hex.replace(/^#/, '');
    const r = parseInt(clean.substring(0, 2), 16) || 0;
    const g = parseInt(clean.substring(2, 4), 16) || 0;
    const b = parseInt(clean.substring(4, 6), 16) || 0;
    const name = c.name || getApproximateColorName(c.hex);
    // Columns: R G B \t Name (R G B right-aligned 3 digits)
    const rStr = r.toString().padStart(3, ' ');
    const gStr = g.toString().padStart(3, ' ');
    const bStr = b.toString().padStart(3, ' ');
    lines.push(`${rStr} ${gStr} ${bStr}\t${name}`);
  }

  return lines.join('\n');
}
